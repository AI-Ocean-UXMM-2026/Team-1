/** Where the parcel is on the four-step journey (0 = just placed). */
export function journeyIndex(status: DeliveryOrder["status"]) {
  switch (status) {
    case "assigned":
    case "accepted":
      return 1;
    case "picked_up":
    case "in_transit":
      return 2;
    case "delivered":
      return 3;
    default:
      return 0;
  }
}
